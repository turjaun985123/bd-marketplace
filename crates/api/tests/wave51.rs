    assert!(first_gallery.ends_with("-600.webp"), "gallery: {first_gallery}");
    assert!(first_card.ends_with("-300.webp"), "card: {first_card}");
    assert!(first_zoom.ends_with("-600.webp"), "zoom: {first_zoom}");
    assert!(first_original.ends_with("-orig"), "original: {first_original}");

    // 3. The serve route returns the derived bytes with
    // the sniffed content type and the immutable cache
    // header; the original serves as PNG.
    let (status, content_type, cache_control, bytes) = call_bytes(&app, &first_gallery).await;
    assert_eq!(status, StatusCode::OK, "serve gallery");
    assert_eq!(content_type.as_deref(), Some("image/webp"));
    assert!(
        cache_control
            .as_deref()
            .is_some_and(|value| value.contains("immutable")),
        "cache header: {cache_control:?}"
    );
